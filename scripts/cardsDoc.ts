import {
  DECK_LIST,
  KEYWORDS,
  RELIC_DEFS,
  allCardDefs,
  getCardDef,
  getDeck,
  keywordName,
  keywordReminder,
  rulesText,
  typeLine,
  type CardDef,
} from '../src/engine';
import { withLocale, type Locale } from '../src/i18n';

export const CARD_DOCS: Record<Locale, string> = { es: 'docs/CARDS.md', en: 'docs/CARDS.en.md' };

const LANGUAGE_NOTES: Record<Locale, string> = {
  es: 'Names, types and rules text are written as the game shows them in Spanish; the ids keep the English names. `docs/CARDS.en.md` lists them as the game shows them in English.',
  en: 'Names, types and rules text are written as the game shows them in English; the Spanish ones are in `docs/CARDS.md`. The English names are in `src/engine/text/cards.en.ts` and `src/engine/text/decks.en.ts`.',
};

function statsOf(def: CardDef): string {
  return def.types.includes('creature') ? `${def.power}/${def.toughness}` : '—';
}

function escapeCell(text: string): string {
  return text.replace(/\|/g, '\\|');
}

function render(locale: Locale): string {
  const lines: string[] = [
    '# Cards',
    '',
    'Generated by `npm run cards` from `src/engine/cards/`, `src/engine/relics.ts` and `src/engine/decks.ts`. Do not edit by hand:',
    '`tests/docs.test.ts` fails when this file is out of date.',
    '',
    LANGUAGE_NOTES[locale],
    '',
  ];
  const decks = DECK_LIST.map((deck) => getDeck(deck.id));
  for (const deck of decks) {
    const total = deck.cards.reduce((sum, entry) => sum + entry.count, 0);
    lines.push(`## ${deck.name} (\`${deck.id}\`, ${total} cards, ${deck.colors.join('')})`, '', deck.description, '');
    lines.push('| Qty | Card | Id | Cost | Type | P/T | Rules text |', '| --- | --- | --- | --- | --- | --- | --- |');
    for (const entry of deck.cards) {
      const def = getCardDef(entry.card);
      const text = rulesText(def).join(' · ');
      lines.push(
        `| ${entry.count} | ${def.name} | \`${def.id}\` | ${def.cost ?? '—'} | ${typeLine(def)} | ${statsOf(def)} | ${escapeCell(text) || '—'} |`,
      );
    }
    lines.push('');
  }
  const creates = (def: CardDef, token: string): boolean =>
    [def.spell, ...(def.triggers ?? []), ...(def.activated ?? [])].some((ability) =>
      ability?.effects.some((effect) => effect.kind === 'createTokens' && effect.token === token),
    );
  const relics = RELIC_DEFS.map((relic) => getCardDef(relic.id));
  const creators = (token: string): string[] => [
    ...decks.flatMap((deck) =>
      deck.cards
        .map((entry) => getCardDef(entry.card))
        .filter((def) => creates(def, token))
        .map((def) => `${def.name} (${deck.name})`),
    ),
    ...relics.filter((def) => creates(def, token)).map((def) => `${def.name} (relic)`),
  ];
  lines.push('## Tokens', '', 'Creatures that effects create. A token that leaves the battlefield ceases to exist.', '');
  lines.push('| Token | Id | Type | P/T | Rules text | Created by |', '| --- | --- | --- | --- | --- | --- |');
  for (const def of allCardDefs().filter((card) => card.token)) {
    const text = rulesText(def).join(' · ');
    lines.push(`| ${def.name} | \`${def.id}\` | ${typeLine(def)} | ${statsOf(def)} | ${escapeCell(text) || '—'} | ${creators(def.id).join(', ')} |`);
  }
  lines.push('');
  lines.push(
    '## Relics',
    '',
    'Expedition relics that act during a duel (`docs/MODES.md`). A player starts with them beside the battlefield; they are never targets and stay for the whole game.',
    '',
  );
  lines.push('| Relic | Id | Type | Rules text |', '| --- | --- | --- | --- |');
  for (const def of relics) lines.push(`| ${def.name} | \`${def.id}\` | ${typeLine(def)} | ${escapeCell(rulesText(def).join(' · '))} |`);
  lines.push('');
  const used = new Set(decks.flatMap((deck) => deck.cards.flatMap((entry) => getCardDef(entry.card).keywords ?? [])));
  lines.push('## Keywords', '', '| Keyword | Meaning | In a deck |', '| --- | --- | --- |');
  for (const keyword of KEYWORDS) {
    lines.push(`| ${keywordName(keyword)} | ${escapeCell(keywordReminder(keyword))} | ${used.has(keyword) ? 'yes' : 'engine only'} |`);
  }
  lines.push('');
  return lines.join('\n');
}

export function renderCardsMarkdown(locale: Locale = 'es'): string {
  return withLocale(locale, () => render(locale));
}
